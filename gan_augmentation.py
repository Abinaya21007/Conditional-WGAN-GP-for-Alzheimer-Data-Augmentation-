class SimpleGenerator(nn.Module):

    def __init__(
        self,
        latent_dim=100,
        num_classes=4
    ):

        super(SimpleGenerator, self).__init__()

        self.latent_dim = latent_dim
        self.num_classes = num_classes

        self.label_embedding = nn.Embedding(
            num_classes,
            latent_dim
        )

        self.fc = nn.Linear(
            latent_dim * 2,
            256 * 4 * 4
        )

        self.main = nn.Sequential(

            nn.ConvTranspose2d(
                256,
                128,
                4,
                2,
                1
            ),

            nn.BatchNorm2d(128),

            nn.ReLU(True),

            nn.ConvTranspose2d(
                128,
                64,
                4,
                2,
                1
            ),

            nn.BatchNorm2d(64),

            nn.ReLU(True),

            nn.ConvTranspose2d(
                64,
                32,
                4,
                2,
                1
            ),

            nn.BatchNorm2d(32),

            nn.ReLU(True),

            nn.ConvTranspose2d(
                32,
                1,
                4,
                2,
                1
            ),

            nn.Tanh()
        )


    def forward(
        self,
        z,
        labels
    ):

        label_emb = self.label_embedding(
            labels
        )

        z = torch.cat(
            [z, label_emb],
            dim=1
        )

        out = self.fc(z)

        out = out.view(
            out.size(0),
            256,
            4,
            4
        )

        img = self.main(out)

        return img


# ============================================
# CRITIC
# BatchNorm replaced with GroupNorm
# ============================================

class SimpleCritic(nn.Module):

    def __init__(
        self,
        num_classes=4,
        img_size=64
    ):

        super(SimpleCritic, self).__init__()

        self.num_classes = num_classes
        self.img_size = img_size

        self.label_embedding = nn.Embedding(
            num_classes,
            img_size * img_size
        )

        self.main = nn.Sequential(

            nn.Conv2d(
                2,
                64,
                4,
                2,
                1
            ),

            nn.LeakyReLU(
                0.2,
                True
            ),

            nn.Conv2d(
                64,
                128,
                4,
                2,
                1
            ),

            nn.GroupNorm(
                8,
                128
            ),

            nn.LeakyReLU(
                0.2,
                True
            ),

            nn.Conv2d(
                128,
                256,
                4,
                2,
                1
            ),

            nn.GroupNorm(
                8,
                256
            ),

            nn.LeakyReLU(
                0.2,
                True
            ),

            nn.Conv2d(
                256,
                512,
                4,
                2,
                1
            ),

            nn.GroupNorm(
                8,
                512
            ),

            nn.LeakyReLU(
                0.2,
                True
            )
        )

        self.fc = nn.Linear(
            512 * 4 * 4,
            1
        )


    def forward(
        self,
        img,
        labels
    ):

        label_emb = self.label_embedding(
            labels
        )

        label_emb = label_emb.view(
            label_emb.size(0),
            1,
            self.img_size,
            self.img_size
        )

        d_in = torch.cat(
            [img, label_emb],
            dim=1
        )

        out = self.main(d_in)

        out = out.view(
            out.size(0),
            -1
        )

        score = self.fc(out)

        return score


